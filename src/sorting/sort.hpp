#pragma once

/**
 * @file sort.hpp
 * @brief Набор классических алгоритмов сортировки массива целых чисел.
 *
 * Все функции принимают полуинтервал [l, r) и сортируют его на месте
 * по возрастанию.
 *
 * Обозначения сложности:
 * - n - количество элементов,
 * - T - время, M - дополнительная память.
 */

/**
 * @brief Быстрая сортировка (Quick Sort).
 *
 * Выбирает опорный элемент, разбивает диапазон на части "меньше" и "больше"
 * опорного и рекурсивно сортирует каждую часть.
 *
 * | Случай  | T          | M        |
 * |---------|------------|----------|
 * | Лучший  | O(n log n) | O(log n) |
 * | Средний | O(n log n) | O(log n) |
 * | Худший  | O(n^2)     | O(n)     |
 *
 * Память - это глубина стека рекурсии.
 *
 * @note Не стабильная. Пример: [2, 2b, 1] при опорном 2 превращается
 *       в [1, 2b, 2] - порядок равных элементов нарушен.
 *
 * @param l Указатель на первый элемент диапазона.
 * @param r Указатель на элемент за последним (конец диапазона, не включается).
 */
void QuickSort(int* l, int* r);

/**
 * @brief Сортировка вставками (Insertion Sort).
 *
 * Поочерёдно берёт элементы и вставляет каждый на своё место
 * в уже отсортированной левой части, сдвигая все элементы больше
 * влево.
 *
 * | Случай  | T      | M    |
 * |---------|--------|------|
 * | Лучший  | O(n)   | O(1) |
 * | Средний | O(n^2) | O(1) |
 * | Худший  | O(n^2) | O(1) |
 *
 * @note Стабильная. При равенстве элемент не сдвигается вправо,
 *       поэтому относительный порядок равных элементов сохраняется.
 *
 * @param l Указатель на первый элемент диапазона.
 * @param r Указатель на элемент за последним.
 */
void InsertionSort(int* l, int* r);

/**
 * @brief Сортировка слиянием (Merge Sort).
 *
 * Делит диапазон пополам, рекурсивно сортирует половины
 * и сливает их в один отсортированный массив.
 *
 * | Случай  | T          | M    |
 * |---------|------------|------|
 * | Лучший  | O(n log n) | O(n) |
 * | Средний | O(n log n) | O(n) |
 * | Худший  | O(n log n) | O(n) |
 *
 * @note Стабильная. При равенстве при слиянии берётся элемент из левой
 *       половины, то есть тот, который был в исходном массиве первым.
 *
 * @param l Указатель на первый элемент диапазона.
 * @param r Указатель на элемент за последним.
 *
 * @return Количество инверсий исходного массива, то есть количество
 *         пар (i, j), где i < j и A[i] > [j]
 */
long long MergeSort(int* l, int* r);

/**
 * @brief Сортировка подсчётом (Counting Sort).
 *
 * Считает, сколько раз встречается каждое значение, и по этим
 * счётчикам расставляет элементы на итоговые позиции.
 *
 * | Случай  | T        | M    |
 * |---------|----------|------|
 * | Лучший  | O(n + k) | O(k) |
 * | Средний | O(n + k) | O(k) |
 * | Худший  | O(n + k) | O(k) |
 *
 * где k - диапазон значений.
 *
 * @note Стабильная. Счётчики преобразуются в префиксные суммы: значение
 *       для каждого ключа - количество элементов, идущих до него
 *       (то есть индекс за последним элементом с этим ключом).
 *       Исходный массив обходится справа налево, чтобы равные элементы
 *       сохранили исходный порядок.
 *
 * @param l Указатель на первый элемент диапазона.
 * @param r Указатель на элемент за последним.
 */
void CountingSort(int* l, int* r);

/**
 * @brief Сортировка выбором (Selection Sort).
 *
 * На каждом шаге находит минимум в неотсортированной части
 * и ставит его в начало этой части.
 *
 * | Случай  | T      | M    |
 * |---------|--------|------|
 * | Лучший  | O(n^2) | O(1) |
 * | Средний | O(n^2) | O(1) |
 * | Худший  | O(n^2) | O(1) |
 *
 * @note Стабильная (в этой реализации). Находится первый минимальный
 *       элемент, все элементы от текущей позиции до него сдвигаются
 *       вправо на одну позицию, а минимум вставляется на освободившееся
 *       место. Обычный обмен (swap) сделал бы сортировку нестабильной.
 *
 * @param l Указатель на первый элемент диапазона.
 * @param r Указатель на элемент за последним.
 */
void SelectionSort(int* l, int* r);

/**
 * @brief Поразрядная сортировка LSD (Least Significant Digit Radix Sort).
 *
 * Сортирует числа по разрядам, начиная с младшего. На каждом проходе
 * используется сортировка подсчётом, оптимизированная под цифры
 * (диапазон значений ключа равен 10).
 *
 * | Случай  | T        | M    |
 * |---------|----------|------|
 * | Лучший  | O(d * n) | O(n) |
 * | Средний | O(d * n) | O(n) |
 * | Худший  | O(d * n) | O(n) |
 *
 * где d - количество разрядов в максимальном числе.
 *
 * @note Стабильная, так как стабильна сортировка подсчётом на каждом
 *       проходе - именно это обеспечивает корректность LSD.
 *
 * @param l Указатель на первый элемент диапазона.
 * @param r Указатель на элемент за последним.
 */
void LSDRadixSort(int* l, int* r);
